import path from 'node:path';

export function sdkContainerOption(engine = 'docker') {
  if (!['docker', 'podman'].includes(engine)) throw Error('Unsupported SDK container engine');
  return `--container-engine=${engine}`;
}

export function sdkBuildJobs(value = 4) {
  if (!/^(?:[1-9]|[12][0-9]|3[0-2])$/.test(String(value))) throw Error('Invalid SDK job count');
  return Number(value);
}

// Proton configure options for one target. x86_64 keeps its existing command.
export function sdkConfigureArgs({name, engine, sdk, arch = 'x86_64'}) {
  if (!['x86_64', 'arm64'].includes(arch)) throw Error('Unsupported target architecture');
  return [`--build-name=${name}`, `--container-engine=${engine}`, `--proton-sdk-image=${sdk}`, '--enable-ccache', ...(arch === 'x86_64' ? [] : [`--target-arch=${arch}`])];
}

export function verifySdkResumeMakefile(text, {source, name, sdk, engine, arch = 'x86_64'}) {
  const expected = `# Generated by: ${source}/configure.sh ${sdkConfigureArgs({name, engine, sdk, arch}).join(' ')}\n\nSRCDIR     := ${source}\nBUILD_NAME := ${name}\nTARGET_ARCH := ${arch}\nINTERNAL_TOOL_NAME := ${name}-proton\nSTEAMRT_IMAGE := ${sdk}\nROOTLESS_CONTAINER := 1\nCONTAINER_ENGINE := ${engine}\nENABLE_CCACHE := 1\n\ninclude $(SRCDIR)/Makefile.in\n`;
  if (text !== expected) throw Error('Resume requires the exact existing pinned SDK configuration');
}

export function sdkBuildPlan(build, epoch, jobs = 4, redist, hostTools = 'x86_64') {
  if (!path.isAbsolute(build) || !/^[0-9]+$/.test(epoch) || !['x86_64', 'aarch64'].includes(hostTools)) throw Error('Invalid SDK build inputs');
  if (redist !== undefined && (!path.isAbsolute(redist) || path.dirname(redist) !== build || !/^redist-[a-f0-9]{8}$/.test(path.basename(redist)))) throw Error('Invalid isolated redistribution path');
  const count = sdkBuildJobs(jobs);
  const common = [`-j${count}`, `J=${count}`, `SOURCE_DATE_EPOCH=${epoch}`];
  return [
    // Proton module64 does not depend on its host-tools stamp. A clean parallel
    // module build can otherwise launch a second WIDL make in the same tree.
    {name: 'Build shared Wine host tools before module submakes', args: [...common, path.join(build, `.wine-${hostTools}-tools`)], timeout: 60*60*1000},
    {name: 'Check xgameruntime in every SDK PE architecture', args: [...common, 'module=xgameruntime', 'module'], timeout: 60*60*1000},
    {name: 'Build complete coherent Proton redistribution', args: [...common, ...(redist ? [`REDIST_DIR=${redist}`] : []), 'redist'], timeout: 5*60*60*1000},
  ];
}
