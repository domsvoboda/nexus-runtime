test('explicit worker counts remain bounded and CI keeps four by default', () => {
  assert.equal(sdkBuildJobs(), 4);
  for (const count of [1, 8, 16, 32, '16']) {
    assert.equal(sdkBuildJobs(count), Number(count));
    for (const stage of sdkBuildPlan('/build', '123', count)) assert.deepEqual(stage.args.slice(0, 2), [`-j${count}`, `J=${count}`]);
  }
  for (const value of [0, 33, -1, 1.5, '', '016', '16 extra', NaN, null]) assert.throws(() => sdkBuildJobs(value));
});

test('resume accepts only the exact pinned configuration without new make directives', () => {
  const input = {source:'/source/proton', name:'runtime-g12345678', sdk:'registry/sdk@sha256:1234', engine:'podman'};
  const text = '# Generated by: /source/proton/configure.sh --build-name=runtime-g12345678 --container-engine=podman --proton-sdk-image=registry/sdk@sha256:1234 --enable-ccache\n\nSRCDIR     := /source/proton\nBUILD_NAME := runtime-g12345678\nTARGET_ARCH := x86_64\nINTERNAL_TOOL_NAME := runtime-g12345678-proton\nSTEAMRT_IMAGE := registry/sdk@sha256:1234\nROOTLESS_CONTAINER := 1\nCONTAINER_ENGINE := podman\nENABLE_CCACHE := 1\n\ninclude $(SRCDIR)/Makefile.in\n';
  assert.doesNotThrow(() => verifySdkResumeMakefile(text, input));
  for (const [key, value] of Object.entries(input)) assert.throws(() => verifySdkResumeMakefile(text, {...input, [key]:value+'-other'}));
  for (const changed of [text+'EXTRA := value\n', text.replace('ROOTLESS_CONTAINER := 1', 'ROOTLESS_CONTAINER := 0'), text.replace('ENABLE_CCACHE := 1', 'ENABLE_CCACHE := 0')]) assert.throws(() => verifySdkResumeMakefile(changed, input));
});

test('rootless Podman is opt-in and CI still defaults to Docker', () => {
  assert.equal(sdkContainerOption(), '--container-engine=docker');
  assert.equal(sdkContainerOption('docker'), '--container-engine=docker');
  assert.equal(sdkContainerOption('podman'), '--container-engine=podman');
  for (const value of ['', 'sh', '/tmp/other', 'podman --privileged']) assert.throws(() => sdkContainerOption(value));
});

test('SDK stages enforce the host-tools barrier while retaining parallel compilation and fatal failures', () => {
  const stages = sdkBuildPlan('/isolated/build', '123');
  assert.equal(stages.length, 3);
  for (const stage of stages) assert.deepEqual(stage.args.slice(0, 3), ['-j4', 'J=4', 'SOURCE_DATE_EPOCH=123']);
  assert.equal(stages[0].args.at(-1), '/isolated/build/.wine-x86_64-tools');
  assert.deepEqual(stages[1].args.slice(-2), ['module=xgameruntime', 'module']);
  assert.equal(stages[2].args.at(-1), 'redist');
});
test('SDK plan rejects relative directories and invalid epochs', () => {
  for (const [directory, epoch] of [['relative','1'],['/build',''],['/build','now'],['/build','1 other=bad']])
    assert.throws(() => sdkBuildPlan(directory, epoch));
});
test('revision-scoped staging never overwrites a previous redistribution',()=>{
  const stages=sdkBuildPlan('/build','1',4,'/build/redist-1234abcd');
  assert.deepEqual(stages[2].args.slice(-2),['REDIST_DIR=/build/redist-1234abcd','redist']);
  for(const bad of ['/tmp/redist-1234abcd','/build/redist','/build/../redist-1234abcd','relative','/build/redist-1234abcd other=value'])assert.throws(()=>sdkBuildPlan('/build','1',4,bad));
});
test('actual parallel make reader/writer race fails before the barrier and passes with the ordered plan', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'nexus-sdk-order-'));
  const fixture = directory => {
    fs.mkdirSync(directory);
    // Model the pinned Proton module graph: module depends on both host tools
    // and recursive readers, but the readers have no host-tool dependency edge.
    fs.writeFileSync(path.join(directory, 'Makefile'), `.PHONY: module module32 module64 redist\nmodule: ${directory}/.wine-x86_64-tools module32 module64\n${directory}/.wine-x86_64-tools:\n\tprintf partial > parser\n\tsleep 0.2\n\tprintf complete > parser\n\ttouch $@\nmodule32 module64:\n\twhile ! test -f parser; do sleep 0.01; done\n\ttest "$$(cat parser)" = complete\nredist: module\n\ttest -f ${directory}/.wine-x86_64-tools\n`);
  };
  try {
    const before = path.join(root, 'before'), after = path.join(root, 'after');
    fixture(before); fixture(after);
    const old = spawnSync('make', ['-j4','module'], {cwd: before, encoding: 'utf8', timeout: 10000});
    assert.equal(old.error, undefined);
    assert.notEqual(old.status, 0, 'unordered readers must see the unfinished generated file');
    for (const stage of sdkBuildPlan(after, '123')) {
      const result = spawnSync('make', stage.args, {cwd: after, encoding: 'utf8', timeout: 10000});
      assert.equal(result.error, undefined);
      assert.equal(result.status, 0, result.stdout + result.stderr);
    }
    assert.equal(fs.readFileSync(path.join(after, 'parser'), 'utf8'), 'complete');
  } finally { fs.rmSync(root, {recursive: true, force: true}); }
});
